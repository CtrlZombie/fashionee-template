// Простейший тест для проверки работы Jest
test('базовый тест Jest работает', () => {
  expect(1 + 1).toBe(2);
});

describe('проверка окружения', () => {
  it('должен работать с массивами', () => {
    expect([1, 2, 3]).toHaveLength(3);
  });

  it('должен работать со строками', () => {
    expect('hello').toContain('hell');
  });
});